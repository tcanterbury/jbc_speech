// Downloads only chart-listed recordings for symbols in our library.
// Source metadata is parsed as text, never executed.
import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { symbols } from '../src/symbols.js';

const base = 'https://www.internationalphoneticassociation.org/IPAcharts/';
const sourceUrl = base + 'IPA_charts_TI/dbs/arrays.js';
const source = await (await checkedFetch(sourceUrl)).text();
const wanted = new Set(symbols.map(item => item.symbol));
const jobs = [];
const index = {};
for (const line of source.split(/\r?\n/)) {
  const symbol = line.match(/\bSymbol:"([^"]+)"/)?.[1].replaceAll('◌', '');
  if (!wanted.has(symbol)) continue;
  const hex = line.match(/\bU_No:"([A-Fa-f0-9 +]+)"/)?.[1];
  const flags = line.match(/\bAudio:(\[\[[\d,\[\]]+\]\])/ )?.[1];
  if (!hex || !flags) continue;
  const audio = JSON.parse(flags);
  for (const [speakerIndex, speaker] of ['JE', 'JH'].entries()) {
    audio[speakerIndex].forEach((available, variant) => {
      if (!available) return;
      const key = hex.replaceAll(' + ', '_') + (variant ? `_${variant}` : '');
      if (!/^[A-Fa-f0-9_]+$/.test(key)) throw new Error('Unexpected recording key');
      const relative = `assets/audio/${speaker}/${key}.mp3`;
      jobs.push({ symbol, speaker, variant, relative, url: `${base}common_files/sounds/${speaker}/${key}.mp3` });
    });
  }
}
if (jobs.length < 100) throw new Error('Official recording map changed; review before downloading.');
for (const speaker of ['JE', 'JH']) await mkdir(new URL(`../src/assets/audio/${speaker}/`, import.meta.url), { recursive: true });
const completed = [];
const missing = [];
let next = 0;
await Promise.all(Array.from({ length: 4 }, async () => {
  while (next < jobs.length) {
    const job = jobs[next++];
    try {
      const response = await fetch(job.url, { signal: AbortSignal.timeout(30000) });
      if (response.status === 404) { missing.push(job); continue; }
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const bytes = Buffer.from(await response.arrayBuffer());
      if (bytes.length < 128 || !(bytes.toString('ascii', 0, 3) === 'ID3' || (bytes[0] === 0xff && (bytes[1] & 0xe0) === 0xe0))) {
        throw new Error('Response is not an MP3 recording');
      }
      await writeFile(new URL('../src/' + job.relative, import.meta.url), bytes);
      completed.push({ ...job, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') });
      if (completed.length % 40 === 0) console.log(`Downloaded ${completed.length} recordings…`);
    } catch (error) { throw new Error(`${job.url}: ${error.message}`); }
  }
}));
for (const item of completed.sort((a, b) => a.relative.localeCompare(b.relative))) {
  index[item.symbol] ??= {};
  index[item.symbol][item.speaker] ??= [];
  index[item.symbol][item.speaker].push(item.relative);
}
await writeFile(new URL('../src/audio-map.js', import.meta.url), '// Generated by scripts/download-audio.mjs. See audio-credits.html.\nexport const recordings = ' + JSON.stringify(index, null, 2) + ';\n');
await writeFile(new URL('../src/assets/audio/provenance.json', import.meta.url), JSON.stringify({
  retrieved: new Date().toISOString(), sourceUrl,
  creditsUrl: base + 'common_files/IPA_charts_about.html',
  license: 'CC BY-NC-ND 4.0', licenseUrl: 'https://creativecommons.org/licenses/by-nc-nd/4.0/',
  speakers: { JE: 'John Esling', JH: 'Jill House' },
  unmodified: true, files: completed, unavailable: missing
}, null, 2));
console.log(JSON.stringify({ clips: completed.length, symbols: Object.keys(index).length, megabytes: completed.reduce((n, x) => n + x.bytes, 0) / 1e6, unavailable: missing.map(x => x.url) }, null, 2));

async function checkedFetch(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response;
}
